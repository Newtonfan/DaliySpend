"""Oracle-dialect checks that need no database.

The project ships on SQLite during development and on Oracle in production.  A
SQLite-only test suite would happily accept DDL that Oracle rejects (for example
``ON DELETE RESTRICT``), so these tests compile the real models with the Oracle
dialect and assert the pieces we care about.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from sqlalchemy.dialects import oracle, sqlite
from sqlalchemy.schema import CreateIndex, CreateTable

from app.extensions import db
from app.models import Account, Category, Transaction, User

MODELS = [User, Category, Account, Transaction]


@pytest.fixture()
def tables(app):
    return [model.__table__ for model in MODELS]


def _ddl(table, dialect) -> str:
    return str(CreateTable(table).compile(dialect=dialect))


def test_primary_keys_use_identity_on_oracle(tables):
    for table in tables:
        ddl = _ddl(table, oracle.dialect())
        assert "GENERATED BY DEFAULT AS IDENTITY" in ddl, table.name
        # ``Identity`` is the portable way to express this; a bare INTEGER would
        # make every INSERT fail with ORA-01400.
        id_column = table.c.id
        assert id_column.identity is not None, table.name


def test_strings_become_char_semantics_varchars(tables):
    ddl = _ddl(Transaction.__table__, oracle.dialect())
    # Chinese text must be measured in characters, not bytes.
    assert "VARCHAR2(" in ddl
    assert " CHAR)" in ddl


def test_no_on_delete_restrict_on_oracle(app):
    # Oracle has no ON DELETE RESTRICT clause; no clause means restrict already.
    for table in db.metadata.tables.values():
        for constraint in table.foreign_key_constraints:
            assert constraint.ondelete in (None, "CASCADE", "SET NULL"), (
                f"{table.name}.{constraint.name} uses {constraint.ondelete!r}"
            )
        ddl = _ddl(table, oracle.dialect())
        assert "ON DELETE RESTRICT" not in ddl, table.name


def test_identifiers_stay_within_oracle_limits(app):
    for table in db.metadata.tables.values():
        names = [table.name]
        names.extend(column.name for column in table.columns)
        names.extend(constraint.name for constraint in table.constraints if constraint.name)
        names.extend(index.name for index in table.indexes if index.name)
        for name in names:
            assert not name.startswith("_"), name
            assert len(name) <= 30, f"{name!r} is {len(name)} chars (Oracle 12.1 limit is 30)"


def test_indexes_compile_for_both_dialects(tables):
    for table in tables:
        for index in table.indexes:
            oracle_sql = str(CreateIndex(index).compile(dialect=oracle.dialect()))
            sqlite_sql = str(CreateIndex(index).compile(dialect=sqlite.dialect()))
            assert "CREATE INDEX" in oracle_sql
            assert "CREATE INDEX" in sqlite_sql


def test_sqlite_ignores_identity_but_keeps_autoincrement(tables):
    for table in tables:
        ddl = _ddl(table, sqlite.dialect())
        assert "IDENTITY" not in ddl, table.name
        assert "PRIMARY KEY" in ddl, table.name


def test_money_is_integer_on_both_dialects():
    oracle_ddl = _ddl(Transaction.__table__, oracle.dialect())
    sqlite_ddl = _ddl(Transaction.__table__, sqlite.dialect())
    for ddl in (oracle_ddl, sqlite_ddl):
        assert "amount_cents INTEGER NOT NULL" in ddl.replace("\n", " ").replace("\t", "") or (
            "amount_cents" in ddl and "INTEGER" in ddl
        )
        assert "amount_cents FLOAT" not in ddl
        assert "BINARY_DOUBLE" not in ddl



# ---------------------------------------------------------------- schema snapshot

ARTIFACT = Path(__file__).resolve().parents[2] / "docs" / "oracle-schema.sql"


def test_committed_oracle_schema_is_in_sync(app):
    """docs/oracle-schema.sql must be regenerated when models/migrations change.

    It is rendered by `scripts\\render-oracle-ddl.ps1` (Alembic offline mode), so
    a missing table here means somebody forgot to re-render it.
    """
    assert ARTIFACT.is_file(), f"missing {ARTIFACT}; run scripts\\render-oracle-ddl.ps1"
    ddl = ARTIFACT.read_text(encoding="utf-8")

    for table in db.metadata.tables.values():
        assert f"CREATE TABLE {table.name} (" in ddl, f"{table.name} missing from the snapshot"

    user_tables = len(db.metadata.tables)
    assert ddl.count("GENERATED BY DEFAULT AS IDENTITY") == user_tables
    assert "ON DELETE RESTRICT" not in ddl
    assert "VARCHAR2(" in ddl and " CHAR)" in ddl
