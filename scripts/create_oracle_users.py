"""Create the Oracle application + test schema users with python-oracledb.

Why this exists: on Windows ``sqlplus / as sysdba`` is blocked here by
``ORA-12241`` (the Oracle service does not authorise the OS user), while the
thin driver talks pure TCP and works.  So instead of shelling out to SQL*Plus,
this script connects as SYSTEM/SYS **once** to create two low-privilege schema
users and then verifies both of them with a fresh connection.

Credentials come from the environment, never from argv, so the SYS password does
not show up in the process list:

    ORA_SYS_USER      SYSTEM (default) or SYS
    ORA_SYS_PASSWORD  required
    ORA_SYS_MODE      SYSDBA (only for SYS)
    ORA_CONNECT       //localhost:1521/FREEPDB1 (default)
    ORA_APP_USER      dailyspend (default)
    ORA_TEST_USER     dailyspend_test (default)
    ORA_APP_PASSWORD  generated when absent
    ORA_TEST_PASSWORD generated when absent
    ORA_WRITE_ENV     1 -> append DS_DATABASE_URL to .env

Typical use (PowerShell wrapper prompts for the password):

    scripts\\setup-oracle-user.ps1 -WriteEnv
"""

from __future__ import annotations

import os
import secrets
import string
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

#: Characters that are safe both in an Oracle password and in a URL userinfo.
PASSWORD_ALPHABET = string.ascii_letters + string.digits + "_-.~"

APP_PRIVILEGES = (
    "CREATE SESSION",
    "CREATE TABLE",
    "CREATE SEQUENCE",
    "CREATE TRIGGER",
)


def generate_password(length: int = 24) -> str:
    """Generate a URL-safe password that satisfies Oracle's typical policy."""
    while True:
        candidate = "".join(secrets.choice(PASSWORD_ALPHABET) for _ in range(length))
        has_digit = any(char.isdigit() for char in candidate)
        has_letter = any(char.isalpha() for char in candidate)
        has_special = any(char in "_-." for char in candidate)
        if has_digit and has_letter and has_special:
            return candidate


def normalise_connect(value: str) -> str:
    """``localhost:1521/FREEPDB1`` -> ``//localhost:1521/FREEPDB1``."""
    text = (value or "").strip()
    if not text:
        return "//localhost:1521/FREEPDB1"
    return text if text.startswith("//") else f"//{text}"


def build_url(user: str, password: str, connect: str) -> str:
    """SQLAlchemy URL for the thin driver (password is already URL-safe)."""
    dsn = normalise_connect(connect).lstrip("/")
    host, _, service = dsn.partition("/")
    if service:
        return f"oracle+oracledb://{user}:{password}@{host}/?service_name={service}"
    return f"oracle+oracledb://{user}:{password}@{host}"


def env_block(url: str) -> str:
    return (
        "# Oracle (generated by scripts/setup-oracle-user.ps1)\n"
        f"DS_DATABASE_URL={url}\n"
    )


def _fail(message: str, code: int = 1) -> int:
    print(f"ERROR: {message}", file=sys.stderr)
    return code


def main() -> int:
    sys_user = os.environ.get("ORA_SYS_USER", "SYSTEM").strip() or "SYSTEM"
    sys_password = os.environ.get("ORA_SYS_PASSWORD", "")
    sys_mode = os.environ.get("ORA_SYS_MODE", "").strip().upper()
    connect = normalise_connect(os.environ.get("ORA_CONNECT", ""))
    app_user = os.environ.get("ORA_APP_USER", "dailyspend").strip().lower()
    test_user = os.environ.get("ORA_TEST_USER", "dailyspend_test").strip().lower()
    app_password = os.environ.get("ORA_APP_PASSWORD", "") or generate_password()
    test_password = os.environ.get("ORA_TEST_PASSWORD", "") or generate_password()
    write_env = os.environ.get("ORA_WRITE_ENV", "") == "1"

    if not sys_password:
        return _fail(
            "ORA_SYS_PASSWORD is empty. Use scripts\\setup-oracle-user.ps1 "
            "(it prompts) or set the variable yourself.",
            2,
        )

    try:
        import oracledb
    except ImportError:
        return _fail("python-oracledb is not installed (pip install oracledb)", 2)

    mode = oracledb.AUTH_MODE_SYSDBA if sys_mode == "SYSDBA" else None
    print(f"connecting as {sys_user}{' AS SYSDBA' if mode else ''} @ {connect} ...")
    try:
        admin = oracledb.connect(
            user=sys_user, password=sys_password, dsn=connect, mode=mode, tcp_connect_timeout=10
        )
    except Exception as exc:  # noqa: BLE001 - report, do not traceback
        return _fail(f"cannot connect as {sys_user}: {_ora_message(exc)}")

    created: list[tuple[str, str, bool]] = []
    try:
        with admin.cursor() as cursor:
            for name, password in ((app_user, app_password), (test_user, test_password)):
                exists = _user_exists(cursor, name)
                if exists:
                    cursor.execute(f'ALTER USER "{name}" IDENTIFIED BY "{password}"')
                else:
                    cursor.execute(f'CREATE USER "{name}" IDENTIFIED BY "{password}"')
                for privilege in APP_PRIVILEGES:
                    cursor.execute(f'GRANT {privilege} TO "{name}"')
                cursor.execute(f'ALTER USER "{name}" QUOTA UNLIMITED ON USERS')
                created.append((name, password, exists))
                print(f"  {'updated' if exists else 'created'}: {name}")
        admin.commit()
    except Exception as exc:  # noqa: BLE001
        return _fail(f"provisioning failed: {_ora_message(exc)}")
    finally:
        admin.close()

    failures = 0
    for name, password, _ in created:
        try:
            probe = oracledb.connect(
                user=name, password=password, dsn=connect, tcp_connect_timeout=10
            )
            with probe.cursor() as cursor:
                cursor.execute("select user from dual")
                current = cursor.fetchone()[0]
            probe.close()
            print(f"  verified: {current} can connect")
        except Exception as exc:  # noqa: BLE001
            failures += 1
            print(f"  FAILED to verify {name}: {_ora_message(exc)}")

    if failures:
        return _fail(f"{failures} schema user(s) could not be verified")

    app_url = build_url(app_user, app_password, connect)
    test_url = build_url(test_user, test_password, connect)

    print()
    print("Add this to .env for the application:")
    print(f"  DS_DATABASE_URL={app_url}")
    print()
    print("Use this for the destructive integration tests:")
    print(f"  DS_ORACLE_TEST_URL={test_url}")

    if write_env:
        env_path = REPO_ROOT / ".env"
        existing = env_path.read_text(encoding="utf-8") if env_path.is_file() else ""
        if "DS_DATABASE_URL=" in existing:
            print("\n.env already defines DS_DATABASE_URL - left untouched.")
        else:
            env_path.write_text(existing + env_block(app_url), encoding="utf-8", newline="\n")
            print(f"\nwrote {env_path}")

    print("\nNext: scripts\\oracle_e2e.ps1 -Url <app-url> -TestUrl <test-url> -IncludeBrowser")
    return 0


def _user_exists(cursor, name: str) -> bool:
    cursor.execute("select count(*) from all_users where username = :1", [name.upper()])
    return bool(cursor.fetchone()[0])


def _ora_message(exc: Exception) -> str:
    args = getattr(exc, "args", ())
    if args and hasattr(args[0], "message"):
        return str(args[0].message)
    return str(exc).replace("\n", " ")


if __name__ == "__main__":
    sys.exit(main())
